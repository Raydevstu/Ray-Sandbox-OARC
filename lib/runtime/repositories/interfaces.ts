import type { ConversationEvent, EntitySummary, EventRecord, EvidenceRecord, MemoryFactRevision, MemoryScope, OutboxRecord, ProjectEvent, ProjectMemoryRecord } from '../contracts';
import type { Checkpoint } from '../jobs/checkpoints';
import type { JobRecord } from '../jobs/queue';
import type { ProjectJob } from '../project-worker';
import type { ControlledBenchmarkRun } from '../benchmark-contract';
import type { MemoryPolicy } from '../memory-policy';
import type { GraphConflictRecord, GraphEdge, GraphEntity } from '../typed-graph';
import type { EvaluationCorrectionProposal, EvaluationRun, ReplayComparison, WorkflowReplay } from '../evaluation-contract';

export type Job = MemoryScope & Readonly<{ id: string; status: string }>;
export type JobHealth = Readonly<{ pending: number; running: number; complete: number; deadLetter: number; oldestPendingAt: string | null; lastError: string | null }>;
export type Projection = MemoryScope & Readonly<{ id: string; value: Readonly<Record<string, unknown>> }>;
export type Snapshot = MemoryScope & Readonly<{ id: string; createdAt: string }>;
export type MemoryPolicyRecord = MemoryScope & Readonly<{ projectId: string; policy: MemoryPolicy }>;
export interface CanonicalRepository {
  appendEvidence(record: EvidenceRecord): Promise<void>;
  appendRevision(record: MemoryFactRevision): Promise<void>;
  findFacts(scope: MemoryScope): Promise<readonly MemoryFactRevision[]>;
  tombstoneFact(scope: MemoryScope, factId: string, deletedAt: string): Promise<void>;
  listEntities(scope: MemoryScope, limit: number): Promise<readonly EntitySummary[]>;
  appendEvent(record: EventRecord): Promise<void>;
  appendOutbox(record: OutboxRecord): Promise<void>;
  claimJobs(scope: MemoryScope, limit: number): Promise<readonly Job[]>;
  saveProjection(projection: Projection): Promise<void>;
  getByIdempotencyKey(scope: MemoryScope, key: string): Promise<EventRecord | undefined>;
  writeSnapshot(snapshot: Snapshot): Promise<void>;
  appendProjectEvent(event: ProjectEvent): Promise<void>;
  listProjectEvents(scope: MemoryScope, projectId: string): Promise<readonly ProjectEvent[]>;
  listProjectMemory(scope: MemoryScope, projectId: string): Promise<readonly ProjectMemoryRecord[]>;
  appendProjectMemory(record: ProjectMemoryRecord): Promise<void>;
  upsertProjectMemory(record: ProjectMemoryRecord): Promise<void>;
  deleteProjectMemory(scope: MemoryScope, projectId: string, recordId: string, deletedAt: string): Promise<void>;
  enqueueProjectJob(job: JobRecord): Promise<void>;
  saveProjectCheckpoint(checkpoint: Checkpoint): Promise<void>;
  getProjectCheckpoint(scope: MemoryScope, consumer: string): Promise<Checkpoint | undefined>;
  claimProjectJobs(scope: MemoryScope, consumer: string, limit: number, leaseMs: number): Promise<readonly ProjectJob[]>;
  completeProjectJob(scope: MemoryScope, jobId: string, consumer: string): Promise<void>;
  failProjectJob(scope: MemoryScope, jobId: string, consumer: string, error: string, maxAttempts: number, retryAt: string): Promise<'pending' | 'dead-letter'>;
  replayDeadLetterJob(scope: MemoryScope, jobId: string, availableAt: string): Promise<boolean>;
  getProjectJobHealth(scope: MemoryScope): Promise<JobHealth>;
  saveBenchmarkRun(scope: MemoryScope, projectId: string, run: ControlledBenchmarkRun): Promise<void>;
  listBenchmarkRuns(scope: MemoryScope, projectId: string, limit: number): Promise<readonly ControlledBenchmarkRun[]>;
  saveEvaluationRun(scope: MemoryScope, projectId: string, run: EvaluationRun): Promise<void>;
  listEvaluationRuns(scope: MemoryScope, projectId: string, limit: number): Promise<readonly EvaluationRun[]>;
  saveReplayComparison(scope: MemoryScope, comparison: ReplayComparison): Promise<void>;
  listReplayComparisons(scope: MemoryScope, projectId: string, limit: number): Promise<readonly ReplayComparison[]>;
  saveEvaluationCorrection(scope: MemoryScope, proposal: EvaluationCorrectionProposal): Promise<void>;
  listEvaluationCorrections(scope: MemoryScope, projectId: string, limit: number): Promise<readonly EvaluationCorrectionProposal[]>;
  saveWorkflowReplay(scope: MemoryScope, replay: WorkflowReplay): Promise<void>;
  listWorkflowReplays(scope: MemoryScope, projectId: string, limit: number): Promise<readonly WorkflowReplay[]>;
  saveMemoryPolicy(record: MemoryPolicyRecord): Promise<void>;
  listMemoryPolicies(scope: MemoryScope, projectId: string, limit: number): Promise<readonly MemoryPolicyRecord[]>;
  saveGraphEntity(scope: MemoryScope, entity: GraphEntity): Promise<void>;
  saveGraphAlias(scope: MemoryScope, entityId: string, alias: string): Promise<void>;
  saveGraphEdge(scope: MemoryScope, edge: GraphEdge): Promise<void>;
  saveGraphConflict(scope: MemoryScope, conflict: GraphConflictRecord): Promise<void>;
  listGraph(scope: MemoryScope): Promise<Readonly<{ entities: readonly GraphEntity[]; edges: readonly GraphEdge[] }>>;
  listGraphConflicts(scope: MemoryScope): Promise<readonly GraphConflictRecord[]>;
}

export type SqlExecutor = (query: string, params: readonly unknown[]) => Promise<readonly Record<string, unknown>[]>;
export type TransactionExecutor = <T>(operation: (execute: SqlExecutor) => Promise<T>) => Promise<T>;
